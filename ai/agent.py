"""Bounded, genuine model-selected tool calling; no automatic evidence sequence."""

import json
import re

from ai.contracts import REPORT_SECTIONS, SYSTEM_INSTRUCTION, strict_json, tool_definitions
from ai.provider import ConfigurationError, ProviderError, provider_from_environment
from ai.tools import EvidenceTools

MAX_TOOL_ROUNDS = 5
MAX_TOOL_EXECUTIONS = 6
DEFAULT_TASK = "Investigate the available weather and terrain evidence and its gaps for this location."
DISCLAIMER = "Evidence-based screening only; not a validated flood prediction or official flood warning system."


def _trace(call, round_number):
    return {"round": round_number,
            "call_id": call.get("call_id") if isinstance(call.get("call_id"), str) else None,
            "tool": call.get("name") if isinstance(call.get("name"), str) else None,
            "arguments": call.get("arguments") if isinstance(call.get("arguments"), str) else None,
            "status": "rejected", "result": None}


def _record_unexecuted(response, result, reason):
    """Retain actual calls even in a refused/incomplete/malformed provider batch."""
    output = response.get("output") if isinstance(response, dict) else None
    if isinstance(output, list):
        for item in output:
            if isinstance(item, dict) and item.get("type") == "function_call":
                entry = _trace(item, result["tool_rounds"] + 1)
                entry.update(status="blocked", result={"status": "blocked", "error": reason})
                result["tool_call_trace"].append(entry)


def _response_parts(response):
    if not isinstance(response, dict) or response.get("status") != "completed":
        raise ValueError("LLM response was incomplete or malformed.")
    output = response.get("output")
    if not isinstance(output, list) or not output:
        raise ValueError("LLM response had no output.")
    calls, text, refused = [], [], False
    for item in output:
        if not isinstance(item, dict):
            raise ValueError("Malformed LLM output item.")
        if item.get("type") == "function_call":
            calls.append(item)
        elif item.get("type") == "message":
            content = item.get("content")
            if item.get("role") != "assistant" or not isinstance(content, list):
                raise ValueError("Malformed LLM message.")
            for part in content:
                if not isinstance(part, dict):
                    raise ValueError("Malformed message content.")
                if part.get("type") == "refusal":
                    refused = True
                elif part.get("type") == "output_text" and isinstance(part.get("text"), str):
                    text.append(part["text"])
                else:
                    raise ValueError("Unsupported message content.")
        elif item.get("type") != "reasoning":
            raise ValueError("Unsupported LLM output item.")
    return output, calls, "".join(text), refused


def _report(text, references, attempted_evidence):
    if not attempted_evidence:
        raise ValueError("A final report requires an actual evidence tool result.")
    if len(text) > 40000:
        raise ValueError("Final report is too large.")
    report = strict_json(text)
    if not isinstance(report, dict) or set(report) != {*REPORT_SECTIONS, "source_ids"}:
        raise ValueError("Final report does not match the required sections.")
    for section in REPORT_SECTIONS:
        if not isinstance(report[section], str) or not report[section].strip():
            raise ValueError("Final report contains an empty or malformed section.")
        # Canonical links are added by code, never generated by the model.
        if re.search(r"https?://|www\.", report[section], re.IGNORECASE):
            raise ValueError("Report links must come from canonical source references.")
    ids = report["source_ids"]
    if (not isinstance(ids, list) or not all(isinstance(i, str) for i in ids)
            or len(set(ids)) != len(ids) or set(ids) != {r["id"] for r in references}):
        raise ValueError("Final report has invented or omitted source references.")
    report["sources_and_retrieval_timestamps"] = references
    report["limitations"] += "\n" + DISCLAIMER
    return report


def investigate(latitude, longitude, *, task=DEFAULT_TASK, provider=None):
    """Return a JSON-safe report, real tool trace and evidence, without UI changes.

    Invalid caller coordinates/tasks raise ValueError before any provider/API use.
    Configuration/provider/protocol failures are structured statuses with no
    fallback narrative. An injected provider must implement respond(**kwargs)
    returning the Responses-shaped dictionary (used by offline tests/adapters).
    """
    evidence = EvidenceTools(latitude, longitude)
    if not isinstance(task, str) or not task.strip() or len(task) > 4000:
        raise ValueError("Investigation task must be nonempty text of at most 4000 characters.")
    coordinates = dict(zip(("latitude", "longitude"), evidence.coordinates))
    result = {"selected_coordinates": coordinates, "agent_status": "running",
              "final_report": None, "tools_used": [], "tool_call_trace": [],
              "evidence_source_references": [], "evidence": {}, "errors": [],
              "warnings": [DISCLAIMER], "tool_rounds": 0, "tool_executions": 0}

    def stop(status, code=None, message=None, diagnostics=None):
        result["agent_status"] = status
        result["evidence_source_references"] = evidence.references()
        result["evidence"] = evidence.cache
        if code:
            result["errors"].append({"code": code, "message": message, **(diagnostics or {})})
        for kind in ("weather", "terrain"):
            entry = evidence.cache.get(kind)
            if entry is None:
                result["warnings"].append(f"{kind.title()} evidence was not retrieved.")
            else:
                if entry["status"] != "available":
                    result["warnings"].append(f"{kind.title()} evidence is {entry['status']}; missing is unknown.")
                if entry["error"]:
                    result["errors"].append({"code": "source_error", "source": kind, **entry["error"]})
        # A defensive final contract check: never serialize NaN or SDK objects.
        json.dumps(result, allow_nan=False)
        return result

    owned = provider is None
    if owned:
        try:
            provider = provider_from_environment()
        except ConfigurationError as exc:
            return stop("configuration_error", "configuration_error", str(exc))
        except Exception:
            return stop("configuration_error", "configuration_error", "The LLM client could not be initialized; raw details were withheld.")
    history = [{"role": "user", "content": json.dumps({
        "selected_coordinates": coordinates, "investigation_task": task,
    }, allow_nan=False)}]
    tools = tool_definitions(*evidence.coordinates)
    seen_ids = set()
    try:
        # Up to five tool rounds plus one final-only provider request.
        for _ in range(MAX_TOOL_ROUNDS + 1):
            allow_tools = (result["tool_rounds"] < MAX_TOOL_ROUNDS
                           and result["tool_executions"] < MAX_TOOL_EXECUTIONS)
            instructions = SYSTEM_INSTRUCTION
            if not allow_tools:
                instructions += "\nTool budget exhausted. Return a report using only existing evidence; do not request tools."
            try:
                response = provider.respond(instructions=instructions, history=history,
                                            tools=tools, allow_tools=allow_tools)
            except ProviderError as exc:
                return stop("provider_error", exc.code, str(exc), diagnostics=exc.diagnostics)
            except Exception:
                return stop("provider_error", "provider_error", "Unexpected provider failure; raw error details were withheld.")
            try:
                output, calls, text, refused = _response_parts(response)
            except (ValueError, TypeError, RecursionError):
                _record_unexecuted(response, result, "Malformed response; no tool execution occurred.")
                return stop("invalid_response", "invalid_response", "The LLM returned an incomplete or malformed response.")
            if refused:
                _record_unexecuted(response, result, "Provider refusal; no tool execution occurred.")
                return stop("refused", "provider_refusal", "The LLM declined to produce an investigation.")
            if not calls:
                try:
                    result["final_report"] = _report(text, evidence.references(), bool(evidence.cache))
                except (ValueError, TypeError, RecursionError):
                    return stop("invalid_response", "invalid_report", "No valid evidence-grounded report was returned.")
                return stop("completed")
            # Keep native response items (including reasoning context) for the SDK.
            # This context is not exposed as an invented 'thinking' trace.
            history.extend(output)
            if allow_tools:
                result["tool_rounds"] += 1
            blocked, malformed_id, tool_failed = False, False, False
            for call in calls:
                call_id = call.get("call_id")
                name = call.get("name")
                arguments = call.get("arguments")
                trace = _trace(call, result["tool_rounds"] if allow_tools else result["tool_rounds"] + 1)
                result["tool_call_trace"].append(trace)
                if tool_failed or malformed_id:
                    trace["status"] = "blocked"
                    tool_result = {"status": "blocked", "error": "A previous call in this batch failed; no execution occurred."}
                elif not allow_tools or result["tool_executions"] >= MAX_TOOL_EXECUTIONS:
                    trace["status"] = "blocked"
                    tool_result = {"status": "blocked", "error": "Tool budget exhausted; no execution occurred."}
                    blocked = True
                elif not isinstance(call_id, str) or not call_id or call_id in seen_ids:
                    tool_result = {"status": "rejected", "error": "Missing or duplicate tool call ID."}
                    malformed_id = True
                else:
                    seen_ids.add(call_id)
                    # Count all dispatch attempts, including cache hits/rejections.
                    result["tool_executions"] += 1
                    try:
                        evidence.validate(name, arguments)
                    except (ValueError, TypeError):
                        tool_result = {"status": "rejected", "error": "Unsupported tool or invalid arguments; use exact selected coordinates."}
                    else:
                        if name not in result["tools_used"]:
                            result["tools_used"].append(name)
                        try:
                            tool_result = evidence.execute(name, arguments)
                            json.dumps(tool_result, allow_nan=False)
                        except Exception:
                            trace["status"] = "error"
                            tool_result = {"status": "error", "error": "Unexpected evidence service or schema failure."}
                            tool_failed = True
                        else:
                            trace["status"] = tool_result["status"]
                trace["result"] = tool_result
                if trace["status"] in ("rejected", "blocked"):
                    result["errors"].append({"code": "tool_" + trace["status"], "call_id": trace["call_id"], "message": tool_result["error"]})
                if isinstance(call_id, str) and call_id:
                    history.append({"type": "function_call_output", "call_id": call_id,
                                    "output": json.dumps(tool_result, allow_nan=False)})
            if tool_failed:
                return stop("tool_error", "tool_error", "Investigation stopped after an unexpected evidence service or schema failure.")
            if blocked:
                return stop("limit_reached", "tool_limit", "Tool budget reached; no further tools were executed.")
            if malformed_id:
                return stop("invalid_response", "invalid_call_id", "Malformed tool call IDs prevented continuation.")
        return stop("limit_reached", "round_limit", "Investigation round limit reached.")
    finally:
        if owned:
            try:
                provider.close()
            except Exception:
                result["warnings"].append("Provider client cleanup failed; raw error details were withheld.")
